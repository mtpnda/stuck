#!/usr/bin/env python3
"""Design Language System generator for Contexts.
design/dls.tokens.json -> design/dls.html + Android (DlsTokens.kt) + iPhone (DlsTokens.swift).
Usage: python3 tools/gen_dls.py [--theme calm]
"""
import json, os, re, sys

class DlsError(Exception):
    pass

REQUIRED_TOKENS = [
    "surface.bg", "surface.card", "surface.raised", "border.subtle", "border.strong",
    "text.primary", "text.secondary", "text.muted", "action.primary", "action.onPrimary", "shadow.tint",
] + [f"state.{s}.{k}" for s in ("calm", "rising", "alert", "info", "neutral") for k in ("chip", "soft", "ink")]

HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")

def resolve_theme(data, theme):
    missing = [t for t in REQUIRED_TOKENS if t not in data["themes"][theme]]
    if missing:
        raise DlsError(f"theme '{theme}' is missing required tokens: {', '.join(missing)}")
    out = {}
    for token, value in data["themes"][theme].items():
        m = re.fullmatch(r"\{palette\.([\w-]+)\}", value)
        if not m or m.group(1) not in data["palette"]:
            raise DlsError(f"theme '{theme}': token '{token}' points at {value}, which is not in the palette")
        colour = data["palette"][m.group(1)]
        if not HEX.match(colour):
            raise DlsError(f"palette '{m.group(1)}' is '{colour}', which is not a #RRGGBB colour")
        out[token] = colour
    return out

def _luminance(hex_colour):
    def channel(c):
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (int(hex_colour[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)

def contrast_ratio(a, b):
    hi, lo = sorted((_luminance(a), _luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)

def check_contrast(data, theme):
    colours = resolve_theme(data, theme)
    errors, warnings = [], []
    for rule in data.get("contrast", []):
        ratio = contrast_ratio(colours[rule["fg"]], colours[rule["bg"]])
        if ratio + 1e-9 < rule["min"]:
            msg = f"{rule['fg']} on {rule['bg']} = {ratio:.2f}:1 (needs {rule['min']}:1 — {rule['use']})"
            (errors if rule.get("severity", "error") == "error" else warnings).append(msg)
    return errors, warnings

def camel(token):
    parts = re.split(r"[.\-]", token)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])

def _argb(hex_colour):
    return "0xFF" + hex_colour[1:].upper()

HEADER = "GENERATED by tools/gen_dls.py from design/dls.tokens.json (theme: {theme}) — DO NOT EDIT. Change the tokens file and regenerate."

def emit_kotlin(data, theme):
    colours = resolve_theme(data, theme)
    lines = [
        "// " + HEADER.format(theme=theme),
        "package com.mtpnda.stuck.ui.theme",
        "",
        "import androidx.compose.ui.graphics.Color",
        "",
        "/** Semantic colours. Components use THESE, never raw hex. */",
        "object DlsTokens {"
    ]
    all_tokens = list(REQUIRED_TOKENS) + [t for t in colours.keys() if t not in REQUIRED_TOKENS]
    for token in all_tokens:
        lines.append(f"    val {camel(token)} = Color({_argb(colours[token])})")
    lines += ["}", "", "/** Radii, spacing, sizes and motion in dp / ms. */", "object DlsScales {"]
    for group, prefix in (("radius", "radius"), ("space", "space"), ("size", "size"), ("motion", "motion")):
        for name, value in data["scales"][group].items():
            if isinstance(value, (int, float)):
                lines.append(f"    const val {camel(prefix + '.' + name)} = {value}")
    for name, value in data["scales"]["font"].items():
        lines.append(f'    const val {camel("font." + name)} = "{value}"')
    lines += ["}", "", "/** Typography roles: size in sp, weight, line height in sp. */", "object DlsType {"]
    for role, t in data["typography"].items():
        lines.append(f"    const val {role}Size = {float(t['size'])}")
        lines.append(f"    const val {role}Weight = {t['weight']}")
        lines.append(f"    const val {role}Line = {float(t['line'])}")
        if "tracking" in t:
            lines.append(f"    const val {role}Tracking = {float(t['tracking'])}")
    lines.append("}")
    return "\n".join(lines) + "\n"

def _swift_colour(hex_colour):
    r, g, b = (int(hex_colour[i:i + 2], 16) for i in (1, 3, 5))
    return f"Color(.sRGB, red: {r}/255.0, green: {g}/255.0, blue: {b}/255.0, opacity: 1)"

def emit_swift(data, theme):
    colours = resolve_theme(data, theme)
    lines = [
        "// " + HEADER.format(theme=theme),
        "import SwiftUI",
        "",
        "/// Semantic colours. Components use THESE, never raw hex.",
        "enum DlsTokens {"
    ]
    all_tokens = list(REQUIRED_TOKENS) + [t for t in colours.keys() if t not in REQUIRED_TOKENS]
    for token in all_tokens:
        lines.append(f"    static let {camel(token)} = {_swift_colour(colours[token])}")
    lines += ["}", "", "/// Radii, spacing, sizes (pt) and motion (ms).", "enum DlsScales {"]
    for group in ("radius", "space", "size", "motion"):
        for name, value in data["scales"][group].items():
            if isinstance(value, (int, float)):
                lines.append(f"    static let {camel(group + '.' + name)}: CGFloat = {value}")
    for name, value in data["scales"]["font"].items():
        lines.append(f'    static let {camel("font." + name)} = "{value}"')
    lines += ["}", "", "/// Typography roles: size (pt), weight, line height (pt).", "enum DlsType {"]
    for role, t in data["typography"].items():
        lines.append(f"    static let {role}Size: CGFloat = {float(t['size'])}")
        lines.append(f"    static let {role}Weight = {t['weight']}")
        lines.append(f"    static let {role}Line: CGFloat = {float(t['line'])}")
        if "tracking" in t:
            lines.append(f"    static let {role}Tracking: CGFloat = {float(t['tracking'])}")
    lines.append("}")
    return "\n".join(lines) + "\n"

def emit_html(data, theme):
    colours = resolve_theme(data, theme)
    css_vars = "\n".join(f"  --{k.replace('.', '-')}: {v};" for k, v in colours.items())
    return f"""<!doctype html>
<html>
<head>
  <meta charset="utf-8">
  <title>Stuck DLS</title>
  <style>
  :root {{
{css_vars}
  }}
  body {{ background: var(--surface-bg); color: var(--text-primary); font-family: sans-serif; padding: 24px; }}
  </style>
</head>
<body>
  <h1>Stuck BioCue DLS (Theme: {theme})</h1>
</body>
</html>
"""

OUTPUTS = [
    "design/dls.html",
    "android/app/src/main/java/com/mtpnda/stuck/ui/theme/DlsTokens.kt",
    "ios/Contexts/Sources/Design/DlsTokens.swift",
]

def _render(data, theme):
    return {
        OUTPUTS[0]: emit_html(data, theme),
        OUTPUTS[1]: emit_kotlin(data, theme),
        OUTPUTS[2]: emit_swift(data, theme),
    }

def generate(root, theme):
    data = json.load(open(os.path.join(root, "design", "dls.tokens.json"), encoding="utf-8"))
    for name in data["themes"]:
        errors, _ = check_contrast(data, name)
        if errors:
            raise DlsError(f"theme '{name}' fails its contrast rules:\n  " + "\n  ".join(errors))
    written = []
    for rel, text in _render(data, theme).items():
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        written.append(rel)
    return written

def main(argv):
    theme = argv[argv.index("--theme") + 1] if "--theme" in argv else "calm"
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    try:
        for rel in generate(root, theme):
            print("wrote", rel)
        return 0
    except DlsError as e:
        print("DLS error:", e)
        return 1

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
